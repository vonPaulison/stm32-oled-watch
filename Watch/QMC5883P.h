#ifndef __QMC5883P_H
#define __QMC5883P_H

#include <stdint.h>

/**
 * ============================================================
 *  QMC5883P.h — 三轴磁传感器 (指南针) 驱动 (头文件)
 *
 *  芯片:   QST 矽睿 QMC5883P, 三轴各向异性磁阻 (AMR) 传感器
 *          LGA-16 封装, 2.5~3.6V 供电, 板载模块接 3.3V
 *  总线:   I2C, 7位从机地址 0x2C (数据手册 5.4 节)
 *          ★ 注意: 与 QMC5883L (0x0D) / HMC5883L (0x1E) 不同,
 *            网上 QMC5883L 的驱动地址/寄存器都不通用, 别混用 ★
 *
 *  总线复用说明 (重要):
 *    本驱动与 OLED 共用同一条软件 I2C 总线 (PB8=SCL, PB9=SDA)
 *    - OLED 模块与 QMC 模块地址不同 (0x78 / 0x2C), 不冲突
 *    - 引脚已在 OLED_GPIO_Init() 中配置为开漏输出 (Out_OD),
 *      靠模块上的上拉电阻拉高 —— 本驱动不再重复配置 GPIO,
 *      因此调用 QMC5883P_Init() 前必须已调用过 OLED_Init()
 *    - 两驱动都只在主循环里运行 (TIM2 中断不碰 I2C),
 *      不存在总线竞争, 可以放心交替使用
 *
 *  寄存器速查 (详见数据手册 9.1 Register Map, 已与
 *  Adafruit/SensorLib 官方驱动三方交叉验证):
 *    0x00  CHIP_ID   只读, 默认 0x80 (用于验证通信)
 *    0x01~0x06       X/Y/Z 数据, 低字节在前, 16位补码
 *    0x09  STATUS    bit1=OVFL(溢出) bit0=DRDY(就绪,读后自动清零)
 *    0x0A  CTRL1     [7:6]OSR2 [5:4]OSR1 [3:2]ODR [1:0]MODE
 *    0x0B  CTRL2     [7]软复位 [6]自测试 [3:2]RNG量程 [1:0]Set/Reset
 *    0x29  SIGN      轴符号配置 (官方示例写 0x06, 见手册 7.2 节)
 *
 *  当前配置: 连续模式 + 10Hz + OSR1=8 (噪声最小) + ±8G 量程
 *    灵敏度 3750 LSB/Gauss, 功耗约 78uA (手册 Table 2)
 * ============================================================
 */

/*══════════════════════════════════════════════════════════════
 *  公共函数声明
 *════════════════════════════════════════════════════════════*/

/**
 * 初始化 QMC5883P (配置成连续测量模式)
 * - 校验 CHIP_ID (0x00) 是否为 0x80, 判断模块是否在总线
 * - 写 0x29=0x06 (轴符号), 0x0B=0x08 (±8G + Set/Reset 开),
 *   0x0A=0x03 (连续模式 10Hz OSR1=8)
 * - 调用时机: 首次进入指南针页面时 (Compass.c 懒初始化),
 *   必须在 OLED_Init() 之后 (依赖它配置好的 I2C 引脚)
 * @return 1=初始化成功(检测到芯片), 0=失败(模块没接/总线异常)
 */
uint8_t QMC5883P_Init(void);

/**
 * 读一组三轴磁场数据 (非阻塞, 无新数据时不覆盖旧值)
 * - 内部先读 0x09 状态寄存器, DRDY=1 才读数据
 *   (DRDY 读后自动清零, 手册 9.2.2 节)
 * - OVFL 溢出 (任一轴超出 [-30000,30000] LSB) 时丢弃本组数据,
 *   防止坏值污染航向角和校准 min/max (手册 9.2.2 OVFL 说明)
 * @param x  输出 X 轴原始值 (±8G 量程下 3750 LSB/Gauss)
 * @param y  输出 Y 轴原始值
 * @param z  输出 Z 轴原始值
 * @return 1=读到新数据, 0=无新数据(DRDY=0), 2=溢出丢弃
 *         x/y/z 仅在返回 1 时被更新
 */
uint8_t QMC5883P_ReadRaw(int16_t *x, int16_t *y, int16_t *z);

/**
 * 让芯片进入挂起模式 (功耗最低, I2C 仍可访问)
 * - 写 0x0A = 0x00 (MODE=00 Suspend, 手册 6.2.4 节)
 * - 退出指南针页面时调用, 手表平时不耗指南针的电
 */
void QMC5883P_Suspend(void);

/*══════════════════════════════════════════════════════════════
 *  诊断工具 (模块不在线时定位问题用)
 *════════════════════════════════════════════════════════════*/

/**
 * I2C 总线扫描 (诊断用)
 * - 遍历合法地址 0x03~0x77, 逐个发地址字节探测有无 ACK
 * - 只发地址不碰寄存器, 对总线上任何设备无副作用
 * - 本总线必能看到 0x3C (OLED): 扫到它 = 驱动时序正常,
 *   扫不到它 = 驱动/引脚问题而非接线问题 (定位利器)
 * @param found 输出: 应答的 7 位地址列表
 * @param max   found 缓冲区容量 (4 就够本总线用)
 * @return 实际找到的设备数
 */
uint8_t QMC5883P_ScanBus(uint8_t *found, uint8_t max);

/**
 * 读芯片 ID 寄存器 (0x00, 诊断用)
 * @return ID 值 (QMC5883P 正常为 0x80), 0xFF = 无应答
 */
uint8_t QMC5883P_ReadID(void);

#endif
