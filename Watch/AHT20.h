#ifndef __AHT20_H
#define __AHT20_H

#include <stdint.h>

/**
 * ============================================================
 *  AHT20.h — 温湿度传感器驱动 (头文件)
 *
 *  芯片:   奥松 ASAIR AHT20, MEMS 电容式湿度元件 + 片上温度
 *          元件, 2.2~5.5V 供电 (模块接 3.3V), 出厂已全标定
 *          湿度 ±2%RH / 温度 ±0.3℃, 分辨率 0.024%RH / 0.01℃
 *  总线:   I2C, 7位从机地址 0x38
 *          (手册图17/18 里的 0x70/0x71 = 0x38 左移拼 R/W 位)
 *
 *  ── 协议特点 (重要, 与 QMC5883P 等"寄存器型"设备不同) ──
 *  AHT20 是"命令式"设备, 通信时序里没有寄存器地址阶段:
 *    发命令: Start → 0x70 → 命令字节 + 参数 → Stop
 *    读数据: Start → 0x71 → 连读 N 字节 → Stop (直接读)
 *  因此本驱动走 System/I2C 的"位级原语"层 (I2C_Start/
 *  I2C_SendByte/...) 自己拼时序, 不能用 I2C_ReadRegs() ——
 *  那个函数会先发一个寄存器地址字节, 破坏 AHT20 的命令格式
 *
 *  依据: AHT20 规格书 2024-07 版 (ASAIR/奥松)
 *    - 测量命令 0xAC 0x33 0x00, 约 80ms 完成 ... 5.1 / 5.2 节
 *    - 读数据 7 字节 = 状态 + 湿度20位 + 温度20位 + CRC . 图18
 *    - 状态字各位含义 .......................... 表9
 *    - CRC8: 初始值 0xFF, 多项式 0x31, 校验前6字节  5.2 节
 *    - 换算: RH=SRH/2^20×100  T=ST/2^20×200-50  .  5.2 节
 *  手册未收录、但经三个独立驱动库交叉验证确认的命令:
 *    - 初始化(加载校准参数) 0xBE 0x08 0x00
 *      (0xE1 是 AHT10 的命令; Adafruit 库用 0xE1 且注释承认
 *       在新版 AHT20 上可能无效, DFRobot_AHT20 与
 *       enjoyneering/AHTxx 对 AHT2x 均用 0xBE —— 取 0xBE)
 *    - 软复位 0xBA, 复位后等 20ms (三库一致)
 *
 *  测量使用顺序 (非阻塞, 适合 10ms 主循环节奏):
 *    AHT20_Init() 一次 → 之后每轮测量:
 *    AHT20_StartMeasure() → 每 tick 调 AHT20_ReadResult()
 *    直到返回 1 (约 80ms ≈ 8 个 tick)。★ 必须先触发再读,
 *    否则读到的是上一次测量的旧数据
 *
 *  功耗: 测量完成自动进休眠 (典型 0.2uA, 手册表2), 不需要
 *        QMC5883P_Suspend() 那样的挂起管理。
 *        注意手册 2.3 节: 采集周期应大于 1s/次, 测太快传感器
 *        自身发热会引入误差 —— 页面层按 1s 一次的节奏调用
 * ============================================================
 */

/*══════════════════════════════════════════════════════════════
 *  公共函数声明
 *══════════════════════════════════════════════════════════════*/

/**
 * 初始化 AHT20 (检查并确保校准使能)
 * - 先调 System/I2C 的 I2C_BusInit() (幂等, 引脚配置 + 总线
 *   卡死恢复), 因此不依赖 OLED_Init 的初始化顺序
 * - 读状态字检查 bit3 校准使能位 (手册表9): 出厂即置 1;
 *   若为 0 则发初始化命令 0xBE 0x08 0x00 加载 OTP 校准参数,
 *   否则输出的是 ADC 原始值而非校准后的数据 (手册表9 bit3)
 * - 这次状态字读取同时充当探测: 模块不在线时无应答 → 返回 0
 * - 调用时机: 首次进入温湿度页面时懒初始化 (与 Compass 同套路)
 * @return 1=初始化成功 (模块在线且校准使能), 0=失败 (不在线/异常)
 */
uint8_t AHT20_Init(void);

/**
 * 触发一次温湿度测量 (非阻塞, 发完命令立即返回)
 * - 发送测量命令 0xAC 0x33 0x00 (手册 5.1/5.2 节)
 * - 测量约 80ms 后完成, 期间忙位 (状态字 bit7) 为 1,
 *   完成后芯片自动休眠等下一次通信 (手册 5.2 节注)
 * @return 1=命令发送成功, 0=模块不在线 (NACK)
 */
uint8_t AHT20_StartMeasure(void);

/**
 * 读取测量结果 (非阻塞: 没测完就返回 0, 下个 tick 再来)
 * - 先直接读 1 字节状态字, 忙位=1 说明 80ms 还没到 → 返回 0
 *   (手册 5.2 节注: 忙位=1 时读到的是上一轮旧数据, 必须等)
 * - 就绪后连读 7 字节 (手册图18): [0]状态 [1..3]湿度20位
 *   [3..5]温度20位 [6]CRC, 并对前 6 字节做 CRC8 校验
 * - 结果为定点数 ×100, 避免 float: 2537 = 25.37℃, 4560 = 45.60%
 *   (换算公式见文件头; 64 位中间量只用到乘法和移位, 无除法)
 * @param temp_c100  输出: 温度×100 (int32, 可为负, -1250=-12.50℃)
 * @param humi_rh100 输出: 相对湿度×100 (uint32, 4560=45.60%RH)
 * @return 1=读到有效新数据 (此时两个输出才被写入)
 *         0=还没测完(忙) 或 模块不在线 —— 下个 tick 直接重试
 *         2=CRC 校验失败, 本轮数据不可信已丢弃 (总线受扰等)
 */
uint8_t AHT20_ReadResult(int32_t *temp_c100, uint32_t *humi_rh100);

/**
 * 软复位 (命令 0xBA, 手册未收录, 三库交叉验证一致)
 * - 复位后等 20ms, 再自动检查/恢复校准使能 (复位可能清掉)
 * - 数据异常时可以"重新来过", 平时用不到
 * @return 1=复位后校准使能正常, 0=模块不在线或校准恢复失败
 */
uint8_t AHT20_SoftReset(void);

/**
 * 读状态字原始字节 (诊断用, 各位含义见手册表9)
 * @param status 输出: 状态字 (bit7忙 bit6:5模式 bit4CRC bit3校准)
 * @return 1=成功, 0=模块不在线
 */
uint8_t AHT20_ReadStatus(uint8_t *status);

#endif
