#ifndef __TEMPHUM_H
#define __TEMPHUM_H

/**
 * ============================================================
 *  TempHum.h — 温湿度页面模块接口
 *
 *  由 Watch_Tick 在 NowState==TempHum 时调用, 全权处理:
 *    传感器初始化 + 测量节奏 + 温湿度显示 + 故障诊断 + 退出
 *
 *  完全自治: 内部管理重绘标志/测量状态机,
 *  不依赖 watch.c 的私有变量 (与 Compass/Stopwatch 同模式)
 * ============================================================
 */

/**
 * 温湿度页面主节拍 (每 10ms 由 Watch_Tick 调用一次)
 *
 * 页面内容:
 *   - 温度行: T: +25.37 °C (8x16 大字, 两行小数点对齐)
 *   - 湿度行: H: 45.60 %
 *   - 底部: 传感器状态字原始值 (诊断) + CRC 错误闪烁提示
 *
 * 测量节奏:
 *   每 ~1.08s 一轮 (手册 2.3 节: 采集周期应大于 1s/次,
 *   测太快传感器自热引入误差); 全程非阻塞, 忙位按 tick
 *   轮询, 不卡 10ms 主循环
 *
 * 交互:
 *   BACK        : 退出页面 (传感器测量完自动休眠 0.2uA,
 *                 无需 QMC 那样的挂起操作)
 *   OK(不在线时): 立即重扫总线
 *
 * 诊断模式 (模块不在线时自动进入):
 *   每 0.5s 自动扫描整条 I2C 总线并显示找到的地址,
 *   OK = 立即重扫, BACK = 退出
 *   0x3C=OLED  0x38=AHT20  0x39=AHT20 地址引脚变体
 */
void TempHum_Tick(void);

#endif
