#ifndef __COMPASS_H
#define __COMPASS_H

/**
 * ============================================================
 *  Compass.h — 指南针页面模块接口
 *
 *  由 Watch_Tick 在 NowState==Compass 时调用, 全权处理:
 *    传感器数据读取 + 航向角解算 + 罗盘绘制 + 校准 + 退出
 *
 *  完全自治: 内部管理重绘标志/校准状态/传感器电源,
 *  不依赖 watch.c 的私有变量 (与 Stopwatch/Countdown 同模式)
 * ============================================================
 */

/**
 * 指南针页面主节拍 (每 10ms 由 Watch_Tick 调用一次)
 *
 * 页面内容:
 *   - 左侧罗盘盘面: 圆环 + N/E/S/W 方位 + 指针 (指向地磁北)
 *   - 右侧: 八方位大字 (N/NE/E/SE/S/SW/W/NW) + 航向角度数
 *   - 底部: 三轴原始值 (调试/校准用)
 *
 * 交互:
 *   BACK       : 退出页面 (传感器进挂起省电, 下次进入自动唤醒)
 *   长按OK     : 开始硬磁校准 (8字/水平旋转一圈)
 *   校准中按OK : 结束校准, 计算并应用偏移
 *   校准中按BACK: 放弃校准
 *
 * 诊断模式 (模块不在线时自动进入):
 *   每 0.5s 自动扫描整条 I2C 总线并显示找到的地址,
 *   OK = 立即重扫, BACK = 退出
 *   0x3C=OLED  0x2C=QMC5883P  0x0D=QMC5883L(老版芯片)
 */
void Compass_Tick(void);

#endif
