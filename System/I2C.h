#ifndef __I2C_H
#define __I2C_H

#include <stdint.h>

/**
 * ============================================================
 *  I2C.h — 软件 I2C 总线模块 (通用版, 供后续扩展的传感器使用)
 *
 *  引脚:   PB8 = SCL, PB9 = SDA, 开漏输出 (GPIO_Mode_Out_OD)
 *          上拉电阻由外部模块板载提供 (OLED/QMC 模块均自带)
 *          换引脚改 I2C.c 顶部的宏即可
 *
 *  时序:   GPIO 翻转 + 小延时压回 ~100kHz 标准模式, 延时计数
 *          可调 (I2C.c 顶部 I2C_DELAY_COUNT), 与 QMC5883P 驱动
 *          同一套已上板验证过的时序
 *
 *  与现有驱动共存 (重要):
 *    本总线上已有两套各写各的 I2C: OLED.c (快时序, 不查 ACK)
 *    和 QMC5883P.c (带 ACK 检查, 能收数据)。本模块是第三套
 *    独立实现, 不被它们调用也不调用它们。三套共用一对引脚,
 *    但都只在主循环里顺序使用 (TIM2 中断不碰 I2C), 只要不嵌套
 *    使用就无总线竞争 —— 新驱动遵守同样规则即可放心混用
 *
 *  地址约定 (重要):
 *    所有函数的 Addr 参数一律填 7 位地址 (数据手册上写的那个),
 *    模块内部左移 1 位自动拼 R/W 位:
 *      QMC5883P   0x2C → 写 0x58 / 读 0x59
 *      SSD1306    0x3C → 写 0x78 / 读 0x79
 *
 *  使用顺序:
 *    先 I2C_BusInit() (自带总线卡死恢复), 之后任意调用。
 *    Init 幂等, 重复调用无害
 *    ★ 不叫 I2C_Init 是为避开标准库 stm32f10x_i2c.h 里的
 *      I2C_Init() (硬件 I2C 外设初始化), 防止重名冲突
 * ============================================================
 */

/*══════════════════════════════════════════════════════════════
 *  位级原语 (想自己拼特殊时序的驱动用这一层)
 *══════════════════════════════════════════════════════════════*/

/**
 * 初始化总线引脚 (开漏输出) 并清理总线卡死状态
 * 引脚配置与 OLED_GPIO_Init() 相同, 谁先初始化都不冲突
 */
void I2C_BusInit(void);

/**
 * 产生起始信号 (SCL 高电平期间 SDA 由高变低)
 */
void I2C_Start(void);

/**
 * 产生终止信号 (SCL 高电平期间 SDA 由低变高)
 */
void I2C_Stop(void);

/**
 * 发送一个字节并检查从机应答
 * @param Byte  要发送的字节
 * @return 1=从机 ACK, 0=NACK (设备不在线/地址错)
 */
uint8_t I2C_SendByte(uint8_t Byte);

/**
 * 接收一个字节
 * @param Ack  1=本字节后回 ACK (还要继续读), 0=回 NACK (最后一个字节)
 * @return 收到的字节
 */
uint8_t I2C_ReceiveByte(uint8_t Ack);

/*══════════════════════════════════════════════════════════════
 *  寄存器级便捷函数 (绝大多数 I2C 传感器都是"寄存器型"设备,
 *  用这一层即可, 不必自己拼 Start/SendByte)
 *══════════════════════════════════════════════════════════════*/

/**
 * 向指定寄存器写入一个字节
 * 时序: Start → 地址+W → 寄存器地址 → 数据 → Stop
 * @return 1=全部 ACK, 0=中途 NACK (设备不在线等)
 */
uint8_t I2C_WriteReg(uint8_t Addr, uint8_t Reg, uint8_t Val);

/**
 * 从指定寄存器读一个字节
 * @return 1=成功, 0=地址阶段 NACK
 */
uint8_t I2C_ReadReg(uint8_t Addr, uint8_t Reg, uint8_t *Val);

/**
 * 从指定寄存器开始连续读 Len 个字节 (地址自动递增)
 * 时序: Start → 地址+W → 寄存器地址 → Restart → 地址+R
 *      → 连读 Len 字节 (末字节 NACK) → Stop
 * @param Len  读取字节数, 1~255
 * @return 1=成功, 0=地址阶段 NACK
 */
uint8_t I2C_ReadRegs(uint8_t Addr, uint8_t Reg, uint8_t *Buf, uint8_t Len);

/*══════════════════════════════════════════════════════════════
 *  总线诊断 (新传感器调试时定位接线/地址问题用)
 *══════════════════════════════════════════════════════════════*/

/**
 * 探测指定地址有无设备应答 (只发地址字节, 不碰寄存器, 对设备无副作用)
 * @return 1=在线, 0=无应答
 */
uint8_t I2C_IsDeviceOnline(uint8_t Addr);

/**
 * 扫描整条总线, 列出所有有应答的 7 位地址 (0x03~0x77 合法区间)
 * 本总线常态应至少扫到 0x3C (OLED) 和 0x2C (QMC5883P);
 * 连 0x3C 都扫不到 = 本模块自身时序/接线有问题
 * @param Found 存放扫描结果的缓冲区
 * @param Max   缓冲区容量 (防止越界)
 * @return 实际找到的设备数
 */
uint8_t I2C_ScanBus(uint8_t *Found, uint8_t Max);

#endif
