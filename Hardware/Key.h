/**
 * ============================================================
 *  Key.h — 4键输入驱动 (头文件)
 *
 *  硬件: STM32F103C8T6 GPIOA
 *        PA0 = UP    (上)
 *        PA1 = DOWN  (下)
 *        PA2 = OK    (确认)
 *        PA3 = BACK  (返回)
 *        内部上拉 (IPU)，按下时引脚接地 → 低电平
 *
 *  消抖策略: 5次 × 10ms = 50ms 稳定检测
 *  长按阈值: 800ms (按住超过800ms触发长按事件)
 *
 *  调用约定: 必须每 10ms 调用一次 Key_Scan()
 *           在主循环底部配合 Delay_ms(10) 实现
 * ============================================================
 */

#ifndef __KEY_H
#define __KEY_H

#include <stdint.h>

/*══════════════════════════════════════════════════════════════
 *  按键 ID 定义 (用作 Key_IsPressed / Key_IsHeld 的参数)
 *══════════════════════════════════════════════════════════════*/
#define KEY_UP      0   /*上键: PA0*/
#define KEY_DOWN    1   /*下键: PA1*/
#define KEY_OK      2   /*确认键: PA2*/
#define KEY_BACK    3   /*返回键: PA3*/
#define KEY_NUM     4   /*按键总数*/

/*══════════════════════════════════════════════════════════════
 *  按键状态机状态定义
 *══════════════════════════════════════════════════════════════
 *
 * 状态转换图:
 *   IDLE ──(按下)──→ DEBOUNCE ──(5次稳定低)──→ PRESSED ──(按住>800ms)──→ LONG
 *    ↑                  │                         │                        │
 *    └──(松开)──────────┘        (松开)──────────→┘       (松开)──────────→┘
 */
#define KEY_STATE_IDLE       0   /*空闲: 未按下，等待按下事件*/
#define KEY_STATE_DEBOUNCE   1   /*消抖: 检测到低电平，正在确认不是抖动*/
#define KEY_STATE_PRESSED    2   /*已按下: 消抖通过，正在等待松开或长按*/
#define KEY_STATE_LONG       3   /*长按: 按住超过阈值，等待松开*/

/*══════════════════════════════════════════════════════════════
 *  时间阈值
 *══════════════════════════════════════════════════════════════*/
#define KEY_LONG_PRESS_MS    800     /*长按触发时间 (毫秒)*/
#define KEY_SCAN_PERIOD_MS   10      /*Key_Scan() 调用周期 (毫秒)，须与主循环一致*/

/*══════════════════════════════════════════════════════════════
 *  公共函数声明
 *══════════════════════════════════════════════════════════════*/

/**
 * 按键初始化
 * - 开启 GPIOA 时钟
 * - 配置 PA0~PA3 为内部上拉输入 (IPU)
 * - 初始化4个按键的状态机为 IDLE
 */
void Key_Init(void);

/**
 * 按键扫描 (需每 10ms 调用一次)
 * - 遍历4个按键，读取引脚电平
 * - 驱动各按键的状态机 (消抖/长按检测)
 * - 更新 press_flag 和 long_flag 边沿标志
 */
void Key_Scan(void);

/**
 * 检测按键是否"刚按下" (边沿触发)
 * 仅在按下瞬间返回1，之后即使按住也返回0
 * @param key_id  按键ID: KEY_UP / KEY_DOWN / KEY_OK / KEY_BACK
 * @return 1=刚按下, 0=未按下或已处理
 */
uint8_t Key_IsPressed(uint8_t key_id);

/**
 * 检测按键是否"长按触发" (边沿触发)
 * 按住超过 KEY_LONG_PRESS_MS (800ms) 时触发一次
 * @param key_id  按键ID
 * @return 1=刚触发长按, 0=未触发
 */
uint8_t Key_IsLongPress(uint8_t key_id);

/**
 * 检测按键是否"正在按住" (电平触发)
 * 每次调用都返回当前按下状态
 * @param key_id  按键ID
 * @return 1=正在按住, 0=未按住
 */
uint8_t Key_IsHeld(uint8_t key_id);

#endif
